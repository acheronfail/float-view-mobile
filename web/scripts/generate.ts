import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import z from 'zod';
import { BackendMessage, BackendCommand } from '../src/lib/backend-client.types';
import { CommPacketId } from '../src/lib/vesc.commands';
import { RefloatCommPacketId } from '../src/lib/refloat.commands';
import { generateKotlinBackendMessages } from './kotlin/backend-messages';
import { generateSwiftBackendMessages } from './swift/backend-messages';
import { VariantSchema } from './common';
import { generateKotlinEnums } from './kotlin/enums';
import { generateSwiftEnums } from './swift/enums';
import { generateKotlinBackendCommands } from './kotlin/backend-commands';
import { generateSwiftBackendCommands } from './swift/backend-commands';

const banner = `\
// This file is generated by scripts/generate.ts
// Re-generate with \`just generate\`
\n`;

const thisFile = fileURLToPath(import.meta.url);
const thisDir = fs.realpathSync(path.dirname(thisFile));
const projectRoot = fs.realpathSync(path.join(thisDir, '..', '..'));
process.chdir(projectRoot);

const writeKotlinFile = (filename: string, content: string) =>
	fs.writeFileSync(
		`android/app/src/main/java/fail/acheron/floatview/Generated_${filename}.kt`,
		banner + content
	);

const writeSwiftFile = (filename: string, content: string) =>
	fs.writeFileSync(`ios/float-view/Generated_${filename}.swift`, banner + content);

const backendMessageSchema = z.toJSONSchema(BackendMessage) as VariantSchema;
writeKotlinFile('BackendMessage', generateKotlinBackendMessages(backendMessageSchema));
writeSwiftFile('BackendMessage', generateSwiftBackendMessages(backendMessageSchema));

writeKotlinFile('Enums', generateKotlinEnums({ CommPacketId, RefloatCommPacketId }));
writeSwiftFile('Enums', generateSwiftEnums({ CommPacketId, RefloatCommPacketId }));

const backendCommandSchema = z.toJSONSchema(BackendCommand) as VariantSchema;
writeKotlinFile('BackendCommands', generateKotlinBackendCommands(backendCommandSchema));
writeSwiftFile('BackendCommands', generateSwiftBackendCommands(backendCommandSchema));
