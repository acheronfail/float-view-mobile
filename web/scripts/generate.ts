import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import z from 'zod';
import { BackendMessage } from '../src/lib/backend-client.types';
import { CommPacketId } from '../src/lib/vesc.commands';
import { RefloatCommPacketId } from '../src/lib/refloat.commands';
import { generateKotlinBackendMessages } from './kotlin/backend-messages';
import { generateSwiftBackendMessages } from './swift/backend-messages';
import { Schema } from './types';
import { generateKotlinEnums } from './kotlin/enums';
import { generateSwiftEnums } from './swift/enums';

const banner = `\
// This file is generated by scripts/generate.ts
// Re-generate with \`just generate\`
`;

const thisFile = fileURLToPath(import.meta.url);
const thisDir = fs.realpathSync(path.dirname(thisFile));
const projectRoot = fs.realpathSync(path.join(thisDir, '..', '..'));
process.chdir(projectRoot);

{
	const backendMessageSchema: Schema = z.toJSONSchema(BackendMessage);
	fs.writeFileSync(
		'android/app/src/main/java/fail/acheron/floatview/Generated_BackendMessage.kt',
		generateKotlinBackendMessages(banner, backendMessageSchema)
	);

	fs.writeFileSync(
		'ios/float-view/Generated_BackendMessage.swift',
		generateSwiftBackendMessages(banner, backendMessageSchema)
	);
}

// TODO: generate Vesc + Refloat command enums
{
	fs.writeFileSync(
		'android/app/src/main/java/fail/acheron/floatview/Generated_Enums.kt',
		generateKotlinEnums(banner, { CommPacketId, RefloatCommPacketId })
	);

	fs.writeFileSync(
		'ios/float-view/Generated_Enums.swift',
		generateSwiftEnums(banner, { CommPacketId, RefloatCommPacketId })
	);
}
