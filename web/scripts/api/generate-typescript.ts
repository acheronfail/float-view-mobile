import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

type Schema = {
	$ref?: string;
	const?: string | number | boolean | null;
	description?: string;
	enum?: Array<string | number | boolean | null>;
	oneOf?: Schema[];
	type?: string | string[];
	items?: Schema;
	properties?: Record<string, Schema>;
	required?: string[];
	additionalProperties?: boolean | Schema;
	$defs?: Record<string, Schema>;
};

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '../../..');
const schemaDir = path.join(projectRoot, 'api/schemas');
const outputDir = path.join(projectRoot, 'api/generated/typescript');
const outputFile = path.join(outputDir, 'models.ts');
const checkOnly = process.argv.includes('--check');

const banner = `/*
 * Generated from api/schemas by web/scripts/api/generate-typescript.ts.
 * Do not edit this file directly.
 */
`;

function literal(value: string | number | boolean | null): string {
	return typeof value === 'string' ? JSON.stringify(value) : String(value);
}

function refName(ref: string): string {
	const name = ref.split('/').at(-1);
	if (!name) throw new Error(`Invalid schema reference: ${ref}`);
	return name;
}

function typeExpression(schema: Schema): string {
	if (schema.$ref) return refName(schema.$ref);
	if (schema.const !== undefined) return literal(schema.const);
	if (schema.enum) return schema.enum.map(literal).join(' | ');
	if (schema.oneOf) return schema.oneOf.map(typeExpression).join(' | ');
	if (Array.isArray(schema.type)) {
		return [...new Set(schema.type.map((type) => typeExpression({ type })))].join(' | ');
	}

	switch (schema.type) {
		case 'string':
			return 'string';
		case 'number':
		case 'integer':
			return 'number';
		case 'boolean':
			return 'boolean';
		case 'null':
			return 'null';
		case 'array':
			return `Array<${typeExpression(schema.items ?? {})}>`;
		case 'object':
			if (!schema.properties) {
				if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
					return `Record<string, ${typeExpression(schema.additionalProperties)}>`;
				}
				return schema.additionalProperties === false
					? 'Record<string, never>'
					: 'Record<string, unknown>';
			}
			return objectExpression(schema);
		default:
			return 'unknown';
	}
}

function objectExpression(schema: Schema): string {
	const required = new Set(schema.required ?? []);
	const fields = Object.entries(schema.properties ?? {}).map(([name, property]) => {
		const comment = property.description ? `/** ${property.description} */\n` : '';
		return `${comment}${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${typeExpression(property)};`;
	});
	if (schema.additionalProperties === true) fields.push('[key: string]: unknown;');
	if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
		fields.push(`[key: string]: ${typeExpression(schema.additionalProperties)};`);
	}
	return `{\n${fields.join('\n')}\n}`;
}

function declaration(name: string, schema: Schema): string {
	if (schema.type === 'object' && schema.properties) {
		return `export interface ${name} ${objectExpression(schema)}`;
	}
	return `export type ${name} = ${typeExpression(schema)};`;
}

const schemas = await Promise.all(
	(await fs.readdir(schemaDir))
		.filter((name) => name.endsWith('.schema.json'))
		.sort()
		.map(
			async (name) => JSON.parse(await fs.readFile(path.join(schemaDir, name), 'utf8')) as Schema
		)
);

const definitions = new Map<string, Schema>();
for (const schema of schemas) {
	for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
		if (definitions.has(name)) throw new Error(`Duplicate API schema definition: ${name}`);
		definitions.set(name, definition);
	}
}

const methods: string[] = [];
for (const [requestName, request] of definitions) {
	if (!requestName.endsWith('Request')) continue;
	const method = request.properties?.method?.const;
	if (typeof method !== 'string') continue;
	const response = definitions.get(requestName.replace(/Request$/, 'Response'));
	const params = request.properties?.params;
	const result = response?.properties?.result;
	if (!response || !result) {
		throw new Error(`Request ${requestName} has no matching response result`);
	}
	methods.push(
		`${JSON.stringify(method)}: { params: ${params ? typeExpression(params) : 'Record<string, never>'}; result: ${typeExpression(result)} };`
	);
}

const source = `${banner}
${Array.from(definitions, ([name, schema]) => declaration(name, schema)).join('\n\n')}

export interface ApiMethods {
${methods.join('\n')}
}

export type ApiMethod = keyof ApiMethods;
export type ApiParams<M extends ApiMethod> = ApiMethods[M]['params'];
export type ApiResult<M extends ApiMethod> = ApiMethods[M]['result'];
`;
const generated = await format(source, {
	parser: 'typescript',
	singleQuote: true,
	trailingComma: 'none',
	printWidth: 100,
	useTabs: true
});

if (checkOnly) {
	let current: string;
	try {
		current = await fs.readFile(outputFile, 'utf8');
	} catch {
		throw new Error(`Generated API file is missing: ${path.relative(projectRoot, outputFile)}`);
	}
	if (current !== generated) {
		throw new Error(
			`Generated API file is stale: ${path.relative(projectRoot, outputFile)}. Run npm run api:generate.`
		);
	}
	console.log('Generated TypeScript API is current.');
} else {
	await fs.mkdir(outputDir, { recursive: true });
	await fs.writeFile(outputFile, generated);
	console.log('Generated TypeScript API models.');
}
